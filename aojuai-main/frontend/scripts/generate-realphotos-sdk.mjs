#!/usr/bin/env node
/**
 * REMAIN-GAP R6：生成 src/generated/realphotos/image_processing.ts
 * generator pin: openapi-typescript@7.4.4
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const frontendRoot = resolve(__dirname, '..')
const openapiPath = resolve(frontendRoot, '../backend/contracts/realphotos_image_processing.openapi.json')
const outDir = join(frontendRoot, 'src/generated/realphotos')
const outFile = join(outDir, 'image_processing.ts')
const metaFile = join(outDir, 'GENERATED.md')
const indexFile = join(outDir, 'index.ts')
const GENERATOR = 'openapi-typescript@7.4.4'

const STUB_SCHEMAS = {
  HTTPValidationError: {
    type: 'object',
    properties: {
      detail: { type: 'array', items: { type: 'object', additionalProperties: true } },
    },
  },
  Body_upload_asset_api_v1_realphotos_assets_post: {
    type: 'object',
    properties: { file: { type: 'string', format: 'binary' } },
  },
  BatchBody: { type: 'object', additionalProperties: true },
  SubmitBody: { type: 'object', additionalProperties: true },
  CopyBody: { type: 'object', additionalProperties: true },
  ReprocessBody: { type: 'object', additionalProperties: true },
  SelectedDownloadBody: { type: 'object', additionalProperties: true },
}

function patchedSpecJson() {
  const raw = JSON.parse(readFileSync(openapiPath, 'utf8'))
  raw.components = raw.components || {}
  raw.components.schemas = { ...(raw.components.schemas || {}), ...STUB_SCHEMAS }
  return JSON.stringify(raw)
}

function generateOnce(targetPath) {
  mkdirSync(outDir, { recursive: true })
  const tmp = join(outDir, '.openapi.patched.json')
  writeFileSync(tmp, patchedSpecJson())
  const result = spawnSync(
    'npx',
    ['--yes', GENERATOR, tmp, '-o', targetPath, '--export-type'],
    { cwd: frontendRoot, encoding: 'utf8' },
  )
  try {
    unlinkSync(tmp)
  } catch {
    /* ignore */
  }
  if (result.status !== 0) {
    process.stderr.write(result.stdout || '')
    process.stderr.write(result.stderr || '')
    process.exit(result.status || 1)
  }
  const digest = createHash('sha256').update(readFileSync(openapiPath)).digest('hex').slice(0, 16)
  const banner = [
    '/**',
    ` * AUTO-GENERATED by scripts/generate-realphotos-sdk.mjs (${GENERATOR}).`,
    ` * Source sha256(16)=${digest}. Do not edit by hand.`,
    ' */',
    '',
  ].join('\n')
  const body = readFileSync(targetPath, 'utf8')
  const withoutOldBanner = body.replace(/^\/\*\*[\s\S]*?\*\/\s*/, '')
  writeFileSync(targetPath, banner + withoutOldBanner)
  return digest
}

function writeSupportFiles(digest) {
  writeFileSync(
    indexFile,
    [
      "/** Re-export generated image_processing OpenAPI types (AD-009). */",
      "export type { paths, components, operations } from './image_processing'",
      '',
    ].join('\n'),
  )
  writeFileSync(
    metaFile,
    [
      '# generated/realphotos',
      '',
      `- generator: \`${GENERATOR}\``,
      `- source sha256(16): \`${digest}\``,
      '- note: missing contract schemas are stubbed at generate time',
      '- regenerate: `pnpm gen:realphotos-sdk` or `node scripts/generate-realphotos-sdk.mjs`',
      '- check: `node scripts/generate-realphotos-sdk.mjs --check`',
      '',
    ].join('\n'),
  )
}

const check = process.argv.includes('--check')
if (check && existsSync(outFile)) {
  const before = readFileSync(outFile, 'utf8')
  const tmpOut = join(outDir, '.image_processing.check.ts')
  const digest = generateOnce(tmpOut)
  const after = readFileSync(tmpOut, 'utf8')
  try {
    unlinkSync(tmpOut)
  } catch {
    /* ignore */
  }
  if (before !== after) {
    console.error('generated realphotos SDK is stale; run node scripts/generate-realphotos-sdk.mjs')
    process.exit(1)
  }
  writeSupportFiles(digest)
  console.log('realphotos SDK check ok')
  process.exit(0)
}

const digest = generateOnce(outFile)
writeSupportFiles(digest)
console.log(`wrote ${outFile}`)
