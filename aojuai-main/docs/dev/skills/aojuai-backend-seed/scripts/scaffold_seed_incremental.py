def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Scaffold an AOJUAI incremental seed script (dry-run by default).")
    parser.add_argument("--module", required=True, help="seed module name (snake_case), e.g. projects")
    parser.add_argument("--write", action="store_true", help="write file (otherwise dry-run)")
    parser.add_argument("--force", action="store_true", help="overwrite existing file")
    args = parser.parse_args(argv)

    module = _validate_module_name(args.module)
    repo_root = _repo_root()
    target = repo_root / "backend" / "scripts" / f"seed_{module}.py"

    if not args.write:
        print("Dry-run. Would generate:")
        print(f"  - {target.relative_to(repo_root)}")
        return 0

    if target.exists() and not args.force:
        print(f"Refusing to overwrite existing file: {target}", file=sys.stderr)
        return 2

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_render(module), encoding="utf-8")
    print(f"✓ Wrote {target.relative_to(repo_root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
