#!/usr/bin/env python3
"""
AOJUAI Skill Script: scaffold_backend_module.py

Purpose:
  Generate a conservative backend module skeleton (domain + endpoints) for this repo.

Notes:
  - This script is intentionally safe: it defaults to dry-run and will not overwrite files unless --force.
  - It does NOT auto-edit router registries (domain/__init__.py, api/v1/__init__.py); it prints next-step snippets.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class ModuleSpec:
    module: str
    model: str
    table: str
    resource: str


def _to_pascal(name: str) -> str:
    parts = re.split(r"[_\\-\\s]+", name.strip())
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def _validate_module_name(name: str) -> str:
    name = name.strip().lower()
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise ValueError("module must match /^[a-z][a-z0-9_]*$/ (snake_case)")
    return name


def _repo_root() -> Path:
    current = Path(__file__).resolve()
    for parent in current.parents:
        if (parent / ".git").exists():
            return parent
    raise SystemExit("Could not locate repo root (missing .git in parents).")


