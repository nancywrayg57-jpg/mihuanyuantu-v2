"""系统菜单的声明式定义（seed / 数据迁移 / 建租户 三写共用的那一份）。

原来只有 CMS 有声明（`app/domain/cms/access.py`），系统菜单则写死在
`scripts/seed_data.py` 的一串 INSERT 里。后果是建租户那条链路补不上系统菜单——
新租户的管理员只看得见内容管理，`user` 角色一条授权都没有，登录后完全空白。
线上没炸只是因为 nextjs-base 只有一个租户，这条链路从没被真正走过。

本文件由 seed 出来的真实库反向生成后人工核对，**不是手抄**——59 个菜单手抄必错。
"用声明建出来的" 与 "seed 建出来的" 是否一致，由
`python -m scripts.check_scenario_parity` 证明（三场景终态对账）。

CMS 菜单不在这里：它归 `CMS_MENU_DECLARATION` 管，两份声明各自 reconcile。

放在 `app/core/` 而不是 `app/domain/menus/`：后者是菜单**内核**，只提供对账机制与
spec 类型，不许持有任何具体声明（`tests/test_menu_reconciler.py` 有检查看着）。
这份是基座自己的系统菜单，不属于任何业务模块，所以归 core。
"""

